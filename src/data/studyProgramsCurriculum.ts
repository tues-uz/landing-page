export function studyProgramDetailPath(programId: string): string {
  return `/admissions/study-programs/${programId}`;
}

export function getStudyProgramById(
  id: string,
): { direction: StudyProgramDirection; program: StudyProgram } | undefined {
  for (const direction of STUDY_PROGRAMS_CURRICULUM) {
    const program = direction.programs.find((p) => p.id === id);
    if (program) return { direction, program };
  }
  return undefined;
}
